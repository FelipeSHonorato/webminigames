/** Remove acentos e cedilha e deixa em maiúsculas: a forma usada para comparar e para as letras. */
export const normalize = w => w.normalize("NFD").replace(/\p{M}/gu, "").toUpperCase();

/** [{ text: "CORAÇÃO", norm: "CORACAO" }, …], sem repetidas, só de 3 a 9 letras. */
export const WORDS = (() => {
  const seen = new Set(), out = [];
  for (const text of RAW.split(/\s+/).filter(Boolean)) {
    const norm = normalize(text);
    if (norm.length < 3 || norm.length > 9 || !/^[A-Z]+$/.test(norm) || seen.has(norm)) continue;
    seen.add(norm);
    out.push({ text, norm });
  }
  return out;
})();
