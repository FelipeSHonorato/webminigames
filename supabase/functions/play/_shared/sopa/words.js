/** Remove acentos e cedilha e deixa em maiúsculas: a forma que vai para a grade. */
export const normalize = w => w.normalize("NFD").replace(/\p{M}/gu, "").toUpperCase();

/** [{ text: "ÁGUA", norm: "AGUA" }, …], sem repetidas. */
export const WORDS = (() => {
  const seen = new Set(), out = [];
  for (const text of RAW.split(/\s+/).filter(Boolean)) {
    const norm = normalize(text);
    if (!seen.has(norm)) { seen.add(norm); out.push({ text, norm }); }
  }
  return out;
})();
